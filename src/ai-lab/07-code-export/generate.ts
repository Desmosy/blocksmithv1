function escapeJsx(text: string): string {
  return text.replace(/[{}<>]/g, (m) => ({ "{": "&#123;", "}": "&#125;", "<": "&lt;", ">": "&gt;" }[m]!));
}

function ctaJsx(cta: DemoCta, extraClass = ""): string {
  if (!cta) return "";
  return `<button type="button" className="ds-${cta.id}${extraClass ? ` ${extraClass}` : ""}">${escapeJsx(cta.label)}</button>`;
}

