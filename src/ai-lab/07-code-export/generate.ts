/**
 * Phase 3 — code export.
 *
 * Because the demo is composed deterministically from the IR + components, the
 * emitted code is faithful *by construction*: token CSS comes straight from the
 * compiled chrome, component classes from the same parsed specs the preview
 * uses, and the page markup from the validated DemoPageModel. No hallucinated
 * values can appear — there is no model in this path.
 */

export type CodeFile = {
  path: string;
  language: "css" | "tsx";
  contents: string;
};

const HEADER = "/* Generated by BlockSmith — faithful to your design system. */";

function cssBlock(title: string, entries: [string, string][]): string {
  if (entries.length === 0) return "";
  const lines = entries.map(([k, v]) => `  ${k}: ${v};`).join("\n");
  return `  /* ${title} */\n${lines}`;
}

export function generateTokenCss(ir: DesignIR): string {
  const colors = Object.entries(ir.colorVariables);
  const fonts = Object.entries(ir.fontStacks);
  const chrome = Object.entries(ir.wikiChrome.cssVariables).filter(
    ([k]) => !ir.fontStacks[k],
  );

  const blocks = [
    cssBlock("Color tokens", colors),
    cssBlock("Typography", fonts),
    cssBlock("Theme / chrome", chrome),
  ].filter(Boolean);

  return `${HEADER}\n:root {\n${blocks.join("\n\n")}\n}\n`;
}

export function generateComponentCss(
  system: DesignSystem,
  ctx: ComponentPreviewContext,
): string {
  const rules = system.components.map((c: ComponentDoc) => {
    const spec = parseComponentPreviewSpec(c, ctx);
    return componentSpecToCss(spec, `.ds-${c.id}`);
  });
  return `${HEADER}\n\n${rules.join("\n\n")}\n`;
}

