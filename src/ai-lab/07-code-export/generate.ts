export function generateDashboardTsx(model: DashboardModel): string {
  const nav = model.navItems
    .map(
      (n) =>
        `          <div className="ds-side__item${n.active ? " ds-side__item--active" : ""}">${escapeJsx(n.label)}</div>`,
    )
    .join("\n");

  const stats = model.stats
    .map(
      (s) => `          <div className="ds-stat">
            <p className="ds-stat__label">${escapeJsx(s.label)}</p>
            <p><span className="ds-stat__value">${escapeJsx(s.value)}</span><span className="ds-stat__delta">${escapeJsx(s.delta)}</span></p>
          </div>`,
    )
    .join("\n");

  const cols = model.table.columns
    .map((c) => `<th>${escapeJsx(c)}</th>`)
    .join("");
  const rows = model.table.rows
    .map((r) => {
      const cells = r.cells.map((c) => `<td>${escapeJsx(c)}</td>`).join("");
      const badge = model.tagSpec ? `ds-${model.tagSpec.kind}` : "ds-badge";
      return `            <tr>${cells}<td><span className="${badge}">${escapeJsx(r.status)}</span></td></tr>`;
    })
    .join("\n");

  return `${HEADER.replace("/*", "//").replace("*/", "")}
import "./tokens.css";
import "./components.css";
import "./styles.css";

export function DashboardPage() {
  return (
    <div className="ds-app">
      <aside className="ds-side">
        <span className="ds-side__brand">${escapeJsx(model.brandName)}</span>
${nav}
      </aside>
      <div className="ds-main">
        <header className="ds-topbar">
          <input className="ds-search" placeholder="${escapeJsx(model.searchPlaceholder)}" readOnly />
          <div>${ctaJsx(model.topbarCta)} ${ctaJsx(model.primaryAction)}</div>
        </header>
        <div className="ds-stats">
${stats}
        </div>
        <div className="ds-table-wrap">
          <div className="ds-table-title">${escapeJsx(model.table.title)}</div>
          <table className="ds-table">
            <thead><tr>${cols}<th>Status</th></tr></thead>
            <tbody>
${rows}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
}
`;
}

export function generateProjectFiles(
  system: DesignSystem,
  ir: DesignIR,
  ctx: ComponentPreviewContext,
  model: DemoModel,
): CodeFile[] {
  const shared: CodeFile[] = [
    { path: "tokens.css", language: "css", contents: generateTokenCss(ir) },
    {
      path: "components.css",
      language: "css",
      contents: generateComponentCss(system, ctx),
    },
  ];

  if (model.archetype === "dashboard") {
    return [
      ...shared,
      { path: "styles.css", language: "css", contents: DASHBOARD_LAYOUT_CSS },
      { path: "DashboardPage.tsx", language: "tsx", contents: generateDashboardTsx(model) },
    ];
  }

  return [
    ...shared,
    { path: "styles.css", language: "css", contents: LANDING_LAYOUT_CSS },
    { path: "LandingPage.tsx", language: "tsx", contents: generateLandingTsx(model) },
  ];
}
